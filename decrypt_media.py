"""
Decrypt the downloaded WeChat SNS media (CDN files in decrypted/media_cdn).

The CDN files are encrypted with ISAAC-64 (WeChat's own implementation, bundled
as WASM): the media element's `key` seeds the PRNG, the resulting keystream is
XOR-ed over the ciphertext.

    images:  entire file XOR-ed with keystream of the same length
    videos:  only the first 131072 bytes are encrypted (key comes from the
             <enc key="..."> tag in the post XML, not the media element)
    thumbs:  video covers are plain images, decrypted like images

The keystream is generated by WeChat's official `wasm_video_decode.wasm`
(WxIsaac64), downloaded from WeChat's CDN on first run. Files that already look
like plaintext (CDN sometimes returns unencrypted bytes despite enc_idx=1) are
copied as-is.

Output: decrypted/media_decrypted/<media_id>[_t].<ext> + decrypt_manifest.json

Usage:
    python decrypt_media.py                      # decrypt everything
    python decrypt_media.py --workers 8 --force  # re-decrypt even if output exists
    python decrypt_media.py --json path/sns_export.json --media-dir decrypted/media_cdn
"""
import argparse
import collections
import functools
import gzip
import hashlib
import json
import os
import re
import shutil
import subprocess
import sys
import urllib.request
from concurrent.futures import ThreadPoolExecutor

print = functools.partial(print, flush=True)

DEFAULT_JSON = os.path.join("decrypted", "sns_export.json")
DEFAULT_MEDIA_DIR = os.path.join("decrypted", "media_cdn")
DEFAULT_OUTPUT = os.path.join("decrypted", "media_decrypted")
DEFAULT_WASM_DIR = os.path.join("decrypted", "wechat_wasm")
MANIFEST_NAME = "decrypt_manifest.json"

VIDEO_HEAD_ENCRYPTED = 131072  # only the first 128 KB of videos are encrypted

# WeChat's own CDN hosts the WASM module + loader (both gzip-encoded)
WASM_URL = "https://aladin.wxqcloud.qq.com/aladin/ffmepeg/video-decode/1.2.46/wasm_video_decode.wasm"
GLUE_URL = "https://aladin.wxqcloud.qq.com/aladin/ffmepeg/video-decode/1.2.46/wasm_video_decode.js"

_MAGICS = (
    (b"\xff\xd8\xff", "jpg"),
    (b"\x89PNG\r\n\x1a\n", "png"),
    (b"GIF87a", "gif"),
    (b"GIF89a", "gif"),
    (b"RIFF", "webp"),
    (b"BM", "bmp"),
)
_MAGICS_MP4 = (b"ftyp", "mp4")
_MAGICS_HEIC = ((b"avif", "avif"), (b"heic", "heic"), (b"heix", "heic"),
                (b"heif", "heif"), (b"mif1", "heif"))


def sniff_ext(data):
    if data[:3] == b"\xff\xd8\xff":
        return "jpg"
    if data[:4] == b"\x89PNG":
        return "png"
    if data[:6] in (b"GIF87a", b"GIF89a"):
        return "gif"
    if data[:4] == b"RIFF" and data[8:12] == b"WEBP":
        return "webp"
    if len(data) >= 8 and data[4:8] == b"ftyp":
        brand = data[8:12]
        for b, ext in _MAGICS_HEIC:
            if brand == b:
                return ext
        return "mp4"
    if data[:2] == b"BM":
        return "bmp"
    return None


def is_plaintext(data):
    return sniff_ext(data) is not None


class IsaacKeystream:
    """Generates WeChat ISAAC-64 keystreams via node + WeChat's official wasm."""

    def __init__(self, wasm_dir):
        self.wasm_dir = wasm_dir
        self.script = os.path.join(os.path.dirname(os.path.abspath(__file__)),
                                   "isaac_keystream.mjs")
        self.node = shutil.which("node")
        self._cache = {}

    def ensure_wasm(self):
        if not self.node:
            print("[ERROR] node.js is required to generate the keystream "
                  "(npm install node / install node.js)")
            sys.exit(1)
        os.makedirs(self.wasm_dir, exist_ok=True)
        wasm = os.path.join(self.wasm_dir, "wasm_video_decode.wasm")
        glue = os.path.join(self.wasm_dir, "wasm_video_decode.js")
        for path, url in ((wasm, WASM_URL), (glue, GLUE_URL)):
            if not os.path.isfile(path) or os.path.getsize(path) == 0:
                print(f"[+] downloading {url.split('/')[-1]} ...")
                with urllib.request.urlopen(url, timeout=120) as resp:
                    data = resp.read()
                if data[:2] == b"\x1f\x8b":  # gzip
                    data = gzip.decompress(data)
                with open(path, "wb") as f:
                    f.write(data)
        return wasm, glue

    def generate(self, seed, size):
        """Return the forward keystream of exactly `size` bytes for `seed`."""
        aligned = ((size + 7) // 8) * 8
        key = (seed, aligned)
        ks = self._cache.get(key)
        if ks is None:
            env = dict(os.environ,
                       WX_ISAAC_WASM=os.path.join(self.wasm_dir, "wasm_video_decode.wasm"),
                       WX_ISAAC_GLUE=os.path.join(self.wasm_dir, "wasm_video_decode.js"))
            proc = subprocess.run(
                [self.node, self.script, str(seed), str(aligned)],
                capture_output=True, env=env, timeout=300)
            if proc.returncode != 0 or not proc.stdout:
                raise RuntimeError(f"keystream failed: {proc.stderr.decode()[:120]}")
            ks = proc.stdout
            self._cache[key] = ks
        return ks[:size]


def build_media_index(export):
    """Return {media_id: (post, media_idx, media_dict)} and {post_tid: post}."""
    by_id = {}
    posts_by_tid = {}
    seen = set()
    for post in export.get("posts", []):
        posts_by_tid[post["tid"]] = post
        for idx, md in enumerate(post.get("media", [])):
            mid = str(md.get("id") or "").strip()
            if not mid or mid in seen:
                mid = f"{post['tid']}_{idx}"
            seen.add(mid)
            by_id[mid] = (post, idx, md)
    return by_id, posts_by_tid


def video_key_from_xml(raw_xml):
    m = re.search(r"<enc\s+key=\"(\d+)\"", raw_xml or "")
    return m.group(1) if m else None


def collect_tasks(media_dir, manifest_entries, by_id):
    """Yield (media_id, variant, enc_path, key, is_video, md5_expected)."""
    tasks = []
    for entry in manifest_entries:
        if entry.get("status") not in ("ok", "skipped"):
            continue
        media_id = entry["media_id"]
        variant = entry.get("variant", "full")
        info = by_id.get(media_id)
        if info is None:
            continue
        post, _, md = info
        saved = entry.get("saved_path", "")
        enc_path = saved if os.path.exists(saved) else os.path.join(media_dir, saved)
        if not os.path.isfile(enc_path):
            enc_path = os.path.join(media_dir, f"{media_id}{'_t' if variant == 'thumb' else ''}")
            if not os.path.isfile(enc_path):
                continue
        url = md.get("url", "") if variant == "full" else md.get("thumb_url", "")
        is_video = ("snsvideodownload" in url) or ("/video" in url) or (".mp4" in url)
        key = None
        if is_video:
            key = video_key_from_xml(post.get("raw_xml", ""))
            if not key:
                key = str(md.get("url_key") or "")
        else:
            key = str(md.get("url_key" if variant == "full" else "thumb_key") or "")
        md5_expected = md.get("url_md5", "") if variant == "full" else ""
        tasks.append((media_id, variant, enc_path, key, is_video, md5_expected))
    return tasks


def decrypt_one(task, out_dir, isaac, only_new, stats, lock):
    media_id, variant, enc_path, key, is_video, md5_expected = task
    entry = {
        "media_id": media_id,
        "variant": variant,
        "status": "fail",
        "error": "",
        "ext": "",
        "size": 0,
        "md5": "",
        "md5_expected": md5_expected or "",
        "checksum": "n/a",
        "saved_path": "",
    }
    try:
        with open(enc_path, "rb") as f:
            data = f.read()
    except OSError as e:
        entry["error"] = f"read: {e}"
        with lock:
            stats["fail"] += 1
        return entry

    if not data:
        entry["error"] = "empty file"
        with lock:
            stats["fail"] += 1
        return entry

    # cache: skip if the decrypted file already exists (avoids keystream work)
    pre = sniff_ext(data)
    if pre is not None:
        name = f"{media_id}{'_t' if variant == 'thumb' else ''}.{pre}"
    else:
        name = None
    if only_new and name:
        out_path = os.path.join(out_dir, name)
        if os.path.isfile(out_path):
            entry.update(status="skipped", ext=pre, size=os.path.getsize(out_path),
                         saved_path=name, checksum="n/a (cached)")
            with lock:
                stats["skipped"] += 1
            return entry

    ext = sniff_ext(data)
    if ext is not None:
        # CDN returned plaintext despite enc_idx — copy as-is
        decrypted = data
        source = "plain"
    else:
        if not key or key == "0":
            entry["error"] = "no key"
            with lock:
                stats["fail"] += 1
            return entry
        try:
            if is_video:
                ks = isaac.generate(key, min(len(data), VIDEO_HEAD_ENCRYPTED))
                decrypted = bytearray(data)
                for j in range(len(ks)):
                    decrypted[j] ^= ks[j]
                decrypted = bytes(decrypted)
            else:
                ks = isaac.generate(key, len(data))
                decrypted = bytes(a ^ b for a, b in zip(data, ks))
            source = "decrypt"
        except Exception as e:
            entry["error"] = f"keystream: {e}"
            with lock:
                stats["fail"] += 1
            return entry

    ext = sniff_ext(decrypted)
    if ext is None:
        entry["error"] = "bad magic after decrypt"
        entry["size"] = len(decrypted)
        with lock:
            stats["fail"] += 1
        return entry

    name = f"{media_id}{'_t' if variant == 'thumb' else ''}.{ext}"
    out_path = os.path.join(out_dir, name)
    if only_new and os.path.isfile(out_path):
        entry.update(status="skipped", ext=ext, size=os.path.getsize(out_path),
                     saved_path=name, checksum="n/a (cached)")
        with lock:
            stats["skipped"] += 1
        return entry

    md5 = hashlib.md5(decrypted).hexdigest()
    entry.update(status="ok", ext=ext, size=len(decrypted), md5=md5,
                 saved_path=name)
    if md5_expected:
        entry["checksum"] = "ok" if md5 == md5_expected.lower() else "mismatch"
        if entry["checksum"] == "mismatch":
            entry["status"] = "checksum_mismatch"
    with lock:
        os.makedirs(out_dir, exist_ok=True)
        with open(out_path, "wb") as f:
            f.write(decrypted)
        stats["ok"] += 1
        stats["bytes"] += len(decrypted)
    return entry


def main(argv=None):
    parser = argparse.ArgumentParser(description="Decrypt downloaded SNS media")
    parser.add_argument("--json", default=DEFAULT_JSON)
    parser.add_argument("--media-dir", default=DEFAULT_MEDIA_DIR)
    parser.add_argument("--output", default=DEFAULT_OUTPUT)
    parser.add_argument("--wasm-dir", default=DEFAULT_WASM_DIR)
    parser.add_argument("--workers", type=int, default=8)
    parser.add_argument("--force", action="store_true",
                        help="re-decrypt even if output exists")
    args = parser.parse_args(argv)

    for path, label in ((args.json, "json"), (args.media_dir, "media dir")):
        if not os.path.exists(path):
            print(f"[ERROR] {label} not found: {path}")
            print("  Run export_sns.py + download_media.py first.")
            return 1

    with open(args.json, encoding="utf-8") as f:
        export = json.load(f)
    manifest_path = os.path.join(args.media_dir, "download_manifest.json")
    with open(manifest_path, encoding="utf-8") as f:
        manifest_entries = json.load(f)

    by_id, _ = build_media_index(export)
    tasks = collect_tasks(args.media_dir, manifest_entries, by_id)
    if not tasks:
        print("[!] no downloadable media found in the manifest")
        return 1

    isaac = IsaacKeystream(args.wasm_dir)
    isaac.ensure_wasm()
    os.makedirs(args.output, exist_ok=True)

    out_manifest_path = os.path.join(args.output, MANIFEST_NAME)
    prev = {}
    try:
        with open(out_manifest_path, encoding="utf-8") as f:
            for e in json.load(f):
                prev[e["media_id"] + e["variant"]] = e
    except (OSError, json.JSONDecodeError):
        pass

    if not args.force:
        done_on_disk = set()
        for e in prev.values():
            if e.get("status") in ("ok", "checksum_mismatch", "skipped") and e.get("saved_path"):
                p = e["saved_path"] if os.path.isabs(e["saved_path"]) \
                    else os.path.join(args.output, e["saved_path"])
                if os.path.isfile(p):
                    done_on_disk.add(e["media_id"] + e["variant"])
        if done_on_disk:
            kept = [t for t in tasks if t[0] + ("thumb" if t[1] == "_t" else "full") not in done_on_disk]
            print(f"[+] skipping {len(tasks) - len(kept)} already-decrypted files")
            tasks = kept
            if not tasks:
                print("[+] nothing to do")
                return 0

    lock = __import__("threading").Lock()
    stats = collections.Counter()
    print(f"[+] {len(tasks)} files to process (workers={args.workers})")
    print(f"[+] output: {os.path.abspath(args.output)}\n")

    total = len(tasks)
    done = 0
    for start in range(0, total, args.workers * 4):
        batch = tasks[start:start + args.workers * 4]
        with ThreadPoolExecutor(max_workers=args.workers) as pool:
            futures = [pool.submit(decrypt_one, t, args.output, isaac,
                                   only_new=not args.force, stats=stats, lock=lock)
                       for t in batch]
            for f in futures:
                entry = f.result()
                prev[entry["media_id"] + entry["variant"]] = entry
        done += len(batch)
        with open(out_manifest_path, "w", encoding="utf-8") as mf:
            json.dump(sorted(prev.values(), key=lambda e: e["media_id"]),
                      mf, ensure_ascii=False, indent=1)
        print(f"  [{done}/{total}] ok={stats['ok']} skip={stats['skipped']} "
              f"fail={stats['fail']} {stats['bytes']/1048576:.1f} MB")

    mm = sum(1 for e in prev.values() if e.get("checksum") == "mismatch")
    print(f"\nDone:")
    print(f"  decrypted: {stats['ok']}  ({stats['bytes']/1048576:.1f} MB)")
    print(f"  skipped (cached): {stats['skipped']}")
    print(f"  failed:    {stats['fail']}")
    print(f"  checksum mismatches: {mm}")
    print(f"  output:    {os.path.abspath(args.output)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
